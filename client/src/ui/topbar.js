import './panels.css';

// The row of buttons at the top right (panel toggles, fine tuning, sign viewer, account). The row is made on first use; each button
// sorts itself by CSS `order` (see panels.css), so the modules can add theirs in any order.
export function topbar() {
  let bar = document.querySelector('.topbar');
  if (!bar) {
    bar = document.createElement('div');
    bar.className = 'topbar';
    document.body.appendChild(bar);
  }
  return bar;
}

/** A round-cornered icon button in the top row; `svg` is the inline SVG markup. */
export function iconButton(svg, label) {
  const b = document.createElement('button');
  b.type = 'button';
  b.className = 'topbar-icon';
  b.title = label;
  b.setAttribute('aria-label', label);
  b.innerHTML = svg;
  return b;
}

